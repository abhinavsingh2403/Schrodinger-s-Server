"""
Honest Status Table Generator for Schrödinger's Server.
Enforces G4:
- Reads results/exp0/progress.json (read-only).
- Computes weighted progress percentage using the formula from analysis/progress_accounting.py.
- Writes docs/STATUS.md.
- Zero hand-typed percentages or fabricated statuses.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PROGRESS_JSON_PATH = PROJECT_ROOT / "results" / "exp0" / "progress.json"
STATUS_MD_PATH = PROJECT_ROOT / "docs" / "STATUS.md"

CREDIT_MAP = {
    "Done": 1.0,
    "Partial": 0.5,
    "Not done": 0.0,
}


def load_progress_data(path: Path = PROGRESS_JSON_PATH) -> Tuple[List[Tuple[str, int, str, str]], float, int, float]:
    """Loads progress items from progress.json and computes accounting metrics."""
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    raw_items = data.get("items", [])
    items: List[Tuple[str, int, str, str]] = [
        (item[0], int(item[1]), str(item[2]), str(item[3]))
        for item in raw_items
    ]

    earned = sum(weight * CREDIT_MAP.get(status, 0.0) for _, weight, status, _ in items)
    total = sum(weight for _, weight, _, _ in items)
    percentage = (100.0 * earned / total) if total > 0 else 0.0

    return items, earned, total, percentage


def generate_status_md(
    items: List[Tuple[str, int, str, str]],
    earned: float,
    total: int,
    percentage: float,
) -> str:
    """Generates deterministic markdown content for docs/STATUS.md."""
    lines = [
        "# Project Status and Evidence Checklist",
        "",
        "This document is automatically generated by `python -m analysis.render_status` from `results/exp0/progress.json`.",
        "Status judgements reflect verifiable evidence and code state, not subjective self-assessment.",
        "",
        "## 1. Evidence-Based Progress Checklist",
        "",
        "| Item | Weight | Status | Evidence / limitation |",
        "|---|---:|---|---|",
    ]

    for name, weight, status, evidence in items:
        lines.append(f"| {name} | {weight} | {status} | {evidence} |")

    lines.extend([
        "",
        "## 2. Summary Accounting",
        "",
        f"- **Weighted Completion**: **{percentage:.1f}%** ({earned:g}/{total:g})",
        "- **Scoring Weights**: Done = 1.0, Partial = 0.5, Not done = 0.0",
        "- **Provenance**: Derived deterministically from `results/exp0/progress.json`.",
        "",
    ])

    return "\n".join(lines)


def render_status(
    json_path: Path = PROGRESS_JSON_PATH,
    out_path: Path = STATUS_MD_PATH,
) -> float:
    """Reads progress.json and writes docs/STATUS.md. Returns computed percentage."""
    items, earned, total, percentage = load_progress_data(json_path)
    content = generate_status_md(items, earned, total, percentage)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    return percentage


def main() -> None:
    pct = render_status()
    print(f"[render_status] Successfully generated {STATUS_MD_PATH.relative_to(PROJECT_ROOT)}: {pct:.1f}%")


if __name__ == "__main__":
    main()
