"""Compute the user-specified weighted checklist from explicit evidence judgements."""
import json
import re
from pathlib import Path

ITEMS = [
    ('S3 aggregate base rates', 2, 'Done', 'results/base_rates.json and analysis/s3_base_rates.py'),
    ('Event-schema check and group field', 2, 'Done', 'results/s3_event_schema.json; event order remains unverified'),
    ('Experiment 0 aggregate stages S1-S3 with leakage controls', 2, 'Partial', 'Stage guards exist; shuffled-label diagnostic fails and event ordering is unverified'),
    ('Experiment 0 event-level S4/S5', 2, 'Not done', 'NOT_EVALUABLE on aggregate data'),
    ('T1/T2 personas and real Cowrie integration on Linux', 2, 'Partial', 'Configs and unit tests exist; Linux collection fails because lark is absent'),
    ('Real hardware cost measurement (Spike S2)', 2, 'Not done', 'Nominal constants only'),
    ('Gatekeeper trained model and offline/live parity', 1, 'Partial', 'Model loads; parity uses one hand-built fixture, not shared offline/live extraction'),
    ('Escalation budget enforcement', 1, 'Partial', 'Decision counter with warmup and memory exceptions; not a strict session cap'),
    ('Persona-effect natural experiment', 1, 'Not done', 'Pending event-level group data'),
    ('Third-party detector evaluation (EVAL H4)', 1, 'Not done', 'Internal checks are not an independent detector evaluation'),
    ('Replay of real held-out traces', 1, 'Not done', 'SYNTHETIC command templates reconstructed from counters'),
    ('Dashboard using only script-generated numbers', 1, 'Partial', 'Reads result JSON and decision DB but has hard-coded numeric fallbacks'),
    ('Public-sensor shadow run under SAFETY checklist', 1, 'Not done', 'No verified run'),
    ('Final report, slides and viva pack', 1, 'Partial', 'Working reports exist; final reviewed pack is absent'),
]


def main():
    credit = {'Done': 1, 'Partial': .5, 'Not done': 0}
    earned = sum(weight * credit[status] for _, weight, status, _ in ITEMS)
    total = sum(weight for _, weight, _, _ in ITEMS)
    percentage = 100 * earned / total
    lines = ['<!-- GENERATED PROGRESS START -->',
             '| Item | Weight | Status | Evidence / limitation |', '|---|---:|---|---|']
    lines += [f'| {name} | {weight} | {status} | {evidence} |' for name, weight, status, evidence in ITEMS]
    lines += ['', f'Weighted completion: **{percentage:.1f}%** ({earned:g}/{total:g}); Done = 1, Partial = 0.5, Not done = 0.',
              'Generated by `python -m analysis.progress_accounting`; status judgements are evidence-based, not performance measurements.',
              '<!-- GENERATED PROGRESS END -->']
    table = '\n'.join(lines)
    for filename in ('README.md', 'HANDOFF.md'):
        path = Path(filename)
        text = path.read_text(encoding='utf-8')
        if '<!-- GENERATED PROGRESS START -->' in text:
            text = re.sub(r'<!-- GENERATED PROGRESS START -->.*?<!-- GENERATED PROGRESS END -->', lambda _: table, text, flags=re.S)
        elif filename == 'README.md':
            start = text.index('### Realistic Maturity Assessment')
            end = text.index('| Phase / Component', start)
            text = text[:start] + '### Evidence-based progress\n\n' + table + '\n\n' + text[end:]
        else:
            start = text.index('## STATUS & PROGRESS ACCOUNTING')
            end = text.index('\n---', start)
            text = text[:start] + '## STATUS & PROGRESS ACCOUNTING\n\n' + table + '\n' + text[end:]
        text = text.replace('Based on latest code audit (7.9/10 provisional rating)', 'Based on the recorded code audit')
        path.write_text(text, encoding='utf-8')
    Path('results/exp0/progress.json').write_text(json.dumps({'items': ITEMS, 'earned': earned, 'total': total, 'percentage': percentage}, indent=2) + '\n')
    print(f'Weighted completion: {percentage:.1f}% ({earned:g}/{total:g})')


if __name__ == '__main__':
    main()
